    public editAdoptersMenu() {
        initComponents();
        // load adopters into the list
        loadAdopters();

        // Wire selection listener
        listAdopters.addListSelectionListener(evt -> {
            if (!evt.getValueIsAdjusting()) {
                Object sel = listAdopters.getSelectedValue();
                AdopterItem ct = (sel instanceof AdopterItem) ? (AdopterItem) sel : null;
                onAdopterSelected(ct);
            }
        });

        // Initially no selection: disable detail controls
        setDetailsEnabled(false);
    }

    private void setDetailsEnabled(boolean enabled) {
        changeDetailsPanel.setEnabled(enabled);
        nameField.setEnabled(enabled);
        contactField.setEnabled(enabled);
        SaveBtn.setEnabled(enabled);
        DeleteBtn.setEnabled(enabled);
    }

    private void loadAdopters() {
        SwingUtilities.invokeLater(() -> {
            DefaultListModel<AdopterItem> model = new DefaultListModel<>();
            String sql = "SELECT adopter_id, name, contact_info FROM adopter ORDER BY name";
            try (Connection conn = main.stuff.dbconn.getConnection(); PreparedStatement ps = conn.prepareStatement(sql); ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    model.addElement(new AdopterItem(rs.getInt("adopter_id"),
                            rs.getString("name"),
                            rs.getString("contact_info")));
                }
            } catch (SQLException ex) {
                logger.log(java.util.logging.Level.WARNING, "Failed to load adopters", ex);
                model.clear();
                model.addElement(new AdopterItem(0, "<Error loading adopters>", ""));
            }

            // set model on EDT
            SwingUtilities.invokeLater(() -> {
                @SuppressWarnings("unchecked")
                javax.swing.JList<AdopterItem> lst = (javax.swing.JList<AdopterItem>) (Object) listAdopters;
                lst.setModel(model);
                // clear selection
                lst.clearSelection();
            });
        });
    }

    private void onAdopterSelected(AdopterItem ct) {
        if (ct == null) {
            selectedAdopterId = null;
            nameLabel.setText("");
            contactLabel.setText("");
            nameField.setText("");
            contactField.setText("");
            setDetailsEnabled(false);
            return;
        }

        selectedAdopterId = ct.id;
        nameLabel.setText(ct.name);
        contactLabel.setText(ct.contact == null ? "" : ct.contact);

        // fill change panel fields with current values
        nameField.setText(ct.name);
        contactField.setText(ct.contact == null ? "" : ct.contact);

        setDetailsEnabled(true);
    }

    private void selectAdopterInListById(int adopterId) {
        if (adopterId <= 0) {
            return;
        }
        @SuppressWarnings("unchecked")
        javax.swing.JList<AdopterItem> lst = (javax.swing.JList<AdopterItem>) (Object) listAdopters;
        javax.swing.ListModel<AdopterItem> model = lst.getModel();
        for (int i = 0; i < model.getSize(); i++) {
            AdopterItem ci = model.getElementAt(i);
            if (ci != null && ci.id == adopterId) {
                final int idx = i;
                SwingUtilities.invokeLater(() -> {
                    lst.setSelectedIndex(idx);
                    lst.ensureIndexIsVisible(idx);
                });
                return;
            }
        }
    }

