    private void SaveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveBtnActionPerformed
        if (selectedAdopterId == null || selectedAdopterId == 0) {
            JOptionPane.showMessageDialog(this, "Please select an adopter to save changes.", "Validation", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String newName = nameField.getText() == null ? "" : nameField.getText().trim();
        String newContact = contactField.getText() == null ? "" : contactField.getText().trim();

        if (newName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Adopter name is required.", "Validation", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String updateSql = "UPDATE adopter SET name = ?, contact_info = ? WHERE adopter_id = ?";

        try (Connection conn = main.stuff.dbconn.getConnection()) {
            try {
                conn.setAutoCommit(false);

                try (PreparedStatement ps = conn.prepareStatement(updateSql)) {
                    ps.setString(1, newName);
                    ps.setString(2, newContact.isEmpty() ? null : newContact);
                    ps.setInt(3, selectedAdopterId);
                    ps.executeUpdate();
                }

                conn.commit();
            } catch (SQLException ex) {
                try {
                    conn.rollback();
                } catch (Throwable ignored) {
                }
                throw ex;
            } finally {
                try {
                    conn.setAutoCommit(true);
                } catch (Throwable ignored) {
                }
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Failed to save adopter changes", ex);
            JOptionPane.showMessageDialog(this, "Failed to save changes: " + ex.getMessage(), "DB error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        JOptionPane.showMessageDialog(this, "Adopter updated.", "Success", JOptionPane.INFORMATION_MESSAGE);
        // reload list and re-select
        loadAdopters();
        SwingUtilities.invokeLater(() -> selectAdopterInListById(selectedAdopterId));
    }//GEN-LAST:event_SaveBtnActionPerformed

    private void DeleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteBtnActionPerformed
        if (selectedAdopterId == null || selectedAdopterId == 0) {
            JOptionPane.showMessageDialog(this, "Please select an adopter to delete.", "Validation", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Delete adopter? This cannot be undone.",
                "Confirm delete",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String deleteSql = "DELETE FROM adopter WHERE adopter_id = ?";

        try (Connection conn = main.stuff.dbconn.getConnection()) {
            try {
                conn.setAutoCommit(false);
                try (PreparedStatement ps = conn.prepareStatement(deleteSql)) {
                    ps.setInt(1, selectedAdopterId);
                    int affected = ps.executeUpdate();
                    if (affected == 0) {
                        throw new SQLException("No adopter removed (it may have already been deleted).");
                    }
                }
                conn.commit();
            } catch (SQLException ex) {
                try {
                    conn.rollback();
                } catch (Throwable ignored) {
                }
                throw ex;
            } finally {
                try {
                    conn.setAutoCommit(true);
                } catch (Throwable ignored) {
                }
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Failed to delete adopter", ex);
            JOptionPane.showMessageDialog(this, "Failed to delete adopter: " + ex.getMessage(), "DB error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        JOptionPane.showMessageDialog(this, "Adopter deleted.", "Success", JOptionPane.INFORMATION_MESSAGE);
        // refresh list and clear selection
        loadAdopters();
        SwingUtilities.invokeLater(() -> onAdopterSelected(null));
    }//GEN-LAST:event_DeleteBtnActionPerformed


